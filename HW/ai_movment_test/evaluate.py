"""
evaluate.py - Evaluates how accurate the trees (and the threshold) are on our OWN recordings.

What it does
------------
1. Reads the CSV files in `mis_grabaciones/` (same format and same preprocessing as run_own.py:
   trimming, 10 Hz, 2 s windows with 50 % overlap).
2. Loads each `decision_tree.h` and runs it as is (parses the C if/else, with
   float32 comparisons as on the microcontroller). This evaluates EXACTLY what will go into the firmware.
3. Computes the confusion matrix, motion detected, still windows discarded, confidence
   intervals (bootstrap by recording), results by person, by activity type and
   the recordings that fail the most.
4. If there are >= 3 people, adds two "honest" models trained with our data and
   evaluated with leave-one-person-out: own threshold and own tree.

"External" vs "in-sample" models
--------------------------------
  --models          trees that have NOT seen our data (e.g. those trained with HAPT).
                    The evaluation is a real generalization test.
  --in-sample-models trees trained with our own data (e.g. out_own/decision_tree.h).
                    Their result is OPTIMISTIC (they have seen this data); it is flagged as such in the report.
                    For an honest figure of "training with my data" look at the LOPO row.

Usage
-----
  python evaluate.py --data ./mis_grabaciones \
      --models out/decision_tree.h out_orientation_free/decision_tree.h \
      --in-sample-models out_own/decision_tree.h --out ./out_eval
"""
import argparse, glob, os, re
import numpy as np
import pandas as pd
from sklearn.tree import DecisionTreeClassifier
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from har_common import FEATURE_NAMES, make_windows, downsample, ThresholdBaseline
from run_own import VALID, INVALID, TRIM_S, PURITY, FS_INTERNAL, load_recording
from run_hapt import metrics, loso

FS_T = 10
AXIS_FEATURES = {"acc_x_std", "acc_y_std", "acc_z_std", "acc_max_axis_range"}


# ------------------------------------------------------------------ data
def build_windows(data_dir):
    X, y, person, rec, tipo = [], [], [], [], []
    for p in sorted(glob.glob(os.path.join(data_dir, "*.csv"))):
        name = os.path.splitext(os.path.basename(p))[0]
        toks = name.lower().split("_")
        cls = toks[0]
        if cls in VALID:
            lab = 0
        elif cls in INVALID:
            lab = 1
        else:
            print(f"[warning] unknown class '{cls}' in {name}; ignored")
            continue
        acc, gyr = load_recording(p)
        k = int(TRIM_S * FS_INTERNAL)
        acc, gyr = acc[k:-k], gyr[k:-k]
        a = downsample(acc, FS_INTERNAL, FS_T)
        g = downsample(gyr, FS_INTERNAL, FS_T)
        Xw, _ = make_windows(a, g, np.ones(len(a), dtype=int), purity=PURITY)
        if len(Xw) == 0:
            print(f"[warning] {name}: too short, ignored")
            continue
        n = len(Xw)
        X.append(Xw)
        y.append(np.full(n, lab))
        person.append(np.full(n, toks[-2] if len(toks) >= 3 else "x"))
        rec.append(np.full(n, name))
        tipo.append(np.full(n, "_".join(toks[:-2]) if len(toks) >= 3 else cls))
    if not X:
        raise SystemExit(f"No valid recordings in {data_dir}")
    return (np.vstack(X), np.concatenate(y), np.concatenate(person),
            np.concatenate(rec), np.concatenate(tipo))


# ------------------------------------------------------------------ tree in C
class CTree:
    """Run in Python a decision_tree.h generated by export_tree_to_c()."""

    def __init__(self, path):
        txt = open(path, encoding="utf-8").read()
        names = {int(i): n for i, n in re.findall(r"f\[(\d+)\]\s*=\s*(\w+)", txt)}
        if not names:
            raise ValueError(f"{path}: cannot find the 'f[i] = name' listing in the comments")
        self.col = {}
        for i, n in names.items():
            if n not in FEATURE_NAMES:
                raise ValueError(f"{path}: unknown feature '{n}'")
            self.col[i] = FEATURE_NAMES.index(n)
        body = txt[txt.index("{", txt.index("static inline int")) + 1:]
        lines = [l.strip() for l in body.splitlines() if l.strip()]
        self.root, pos = self._parse(lines, 0)
        self.path = path
        self.n_nodes = self._count(self.root)
        self.features = sorted({names[f] for f in self._used(self.root)})

    def _parse(self, lines, pos):
        ln = lines[pos]
        m = re.match(r"return\s+(\d+);", ln)
        if m:
            return ("leaf", int(m.group(1))), pos + 1
        m = re.match(r"if \(f\[(\d+)\]\s*<=\s*([-+0-9.eE]+)f?\)\s*\{", ln)
        if not m:
            raise ValueError(f"Unrecognized line in the tree: {ln}")
        left, pos = self._parse(lines, pos + 1)
        if lines[pos] != "} else {":
            raise ValueError("Expected '} else {'")
        right, pos = self._parse(lines, pos + 1)
        if lines[pos] != "}":
            raise ValueError("Expected '}'")
        return ("node", int(m.group(1)), float(m.group(2)), left, right), pos + 1

    def _count(self, n):
        return 1 if n[0] == "leaf" else 1 + self._count(n[3]) + self._count(n[4])

    def _used(self, n):
        return [] if n[0] == "leaf" else [n[1]] + self._used(n[3]) + self._used(n[4])

    def predict(self, X):
        Xf = X.astype(np.float32)
        out = np.zeros(len(X), dtype=int)

        def rec(node, idx):
            if len(idx) == 0:
                return
            if node[0] == "leaf":
                out[idx] = node[1]
                return
            _, fi, thr, l, r = node
            left = Xf[idx, self.col[fi]] <= np.float32(thr)
            rec(l, idx[left])
            rec(r, idx[~left])

        rec(self.root, np.arange(len(X)))
        return out


class FixedThreshold:
    def __init__(self, thr):
        self.thr = thr

    def predict(self, X):
        return (X[:, FEATURE_NAMES.index("acc_mag_std")].astype(np.float32)
                > np.float32(self.thr)).astype(int)


# ------------------------------------------------------------------ metrics
def bootstrap_ci(y, pred, rec, B=1000, seed=0):
    """95 % CI resampling RECORDINGS (the windows of one recording are not independent)."""
    df = pd.DataFrame({"rec": rec, "tp": (y == 1) & (pred == 1), "fn": (y == 1) & (pred == 0),
                       "tn": (y == 0) & (pred == 0), "fp": (y == 0) & (pred == 1)})
    c = df.groupby("rec")[["tp", "fn", "tn", "fp"]].sum().to_numpy(float)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(c), (B, len(c)))
    s = c[idx].sum(axis=1)
    with np.errstate(invalid="ignore", divide="ignore"):
        sens = s[:, 0] / (s[:, 0] + s[:, 1])
        disc = s[:, 3] / (s[:, 2] + s[:, 3])
    f = lambda v: (np.nanpercentile(v, 2.5), np.nanpercentile(v, 97.5))
    return f(sens), f(disc)


def per_group(y, pred, groups):
    rows = []
    for g in np.unique(groups):
        k = groups == g
        m = metrics(y[k], pred[k])
        rows.append((g, int(k.sum()), int((y[k] == 1).sum()), int((y[k] == 0).sum()),
                     m["sens_mov"] if (y[k] == 1).any() else np.nan,
                     m["quietas_descartadas"] if (y[k] == 0).any() else np.nan,
                     float((pred[k] != y[k]).mean())))
    return pd.DataFrame(rows, columns=["grupo", "ventanas", "n_mov", "n_quieto",
                                       "mov_detectado", "quietas_descartadas", "error"])


def plot_cms(results, path):
    n = len(results)
    cols = min(n, 3)
    rows = int(np.ceil(n / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(3.6 * cols, 3.4 * rows), squeeze=False)
    for ax in axes.ravel():
        ax.axis("off")
    for ax, r in zip(axes.ravel(), results):
        ax.axis("on")
        cm = r["m"]["cm"]
        ax.imshow(cm, cmap="Blues")
        ax.set_xticks([0, 1]); ax.set_xticklabels(["valid", "not valid"], fontsize=8)
        ax.set_yticks([0, 1]); ax.set_yticklabels(["still", "motion"], fontsize=8)
        ax.set_title(r["label"][:34] + ("\n(in-sample)" if r["in_sample"] else ""), fontsize=8)
        for i in range(2):
            for j in range(2):
                ax.text(j, i, cm[i, j], ha="center", va="center",
                        color="white" if cm[i, j] > cm.max() / 2 else "black")
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


# ------------------------------------------------------------------ main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="./mis_grabaciones")
    ap.add_argument("--models", nargs="*", default=None,
                    help="decision_tree.h files that have NOT seen our data")
    ap.add_argument("--in-sample-models", nargs="*", default=[],
                    help="decision_tree.h files trained with this same data (optimistic result)")
    ap.add_argument("--hapt-threshold", type=float, default=0.0424,
                    help="acc_mag_std threshold (g) learned with HAPT; use 0 to skip it")
    ap.add_argument("--depth", type=int, default=3, help="depth of the own tree (LOPO)")
    ap.add_argument("--orientation-free", action="store_true",
                    help="the own LOPO tree does not use per-axis features")
    ap.add_argument("--out", default="./out_eval")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    if a.models is None:
        a.models = [p for p in ("out/decision_tree.h", "out_orientation_free/decision_tree.h")
                    if os.path.exists(p)]
    log = open(os.path.join(a.out, "informe.txt"), "w", encoding="utf-8")

    def P(*x):
        s = " ".join(str(v) for v in x)
        print(s)
        log.write(s + "\n")

    X, y, person, rec, tipo = build_windows(a.data)
    persons = np.unique(person)
    P(f"Data: {len(y)} windows | {len(np.unique(rec))} recordings | people: {list(persons)}")
    P(f"  still (valid): {(y == 0).sum()} | motion (not valid): {(y == 1).sum()}")
    P("  windows by type:", dict(pd.Series(tipo).value_counts()))
    if len(persons) < 3:
        P("[warning] with <3 people the LOPO models are not computed and the figures are unreliable.")

    # ---- gather the predictions of each model
    results = []

    def add(label, pred, in_sample=False, note=""):
        m = metrics(y, pred)
        ci_s, ci_d = bootstrap_ci(y, pred, rec)
        results.append(dict(label=label, pred=pred, m=m, ci_s=ci_s, ci_d=ci_d,
                            in_sample=in_sample, note=note))

    if a.hapt_threshold:
        add(f"HAPT threshold ({a.hapt_threshold:g} g)", FixedThreshold(a.hapt_threshold).predict(X),
            note="fixed threshold on acc_mag_std, learned with HAPT")
    for path, ins in [(p, False) for p in a.models] + [(p, True) for p in a.in_sample_models]:
        try:
            t = CTree(path)
        except Exception as e:
            P(f"[ERROR] {path}: {e}")
            continue
        lab = os.path.basename(os.path.dirname(os.path.abspath(path))) or path
        add(f"Tree {lab}", t.predict(X), in_sample=ins,
            note=f"{t.n_nodes} nodes, uses: {', '.join(t.features)}")
    if len(persons) >= 3:
        add("Own threshold (LOPO)", loso(X, y, person, lambda: ThresholdBaseline(0)),
            note="threshold retrained leaving one person out")
        cols = [i for i, n in enumerate(FEATURE_NAMES)
                if not (a.orientation_free and n in AXIS_FEATURES)]
        Xs = X[:, cols]
        mk = lambda: DecisionTreeClassifier(max_depth=a.depth, class_weight="balanced",
                                            min_samples_leaf=5, random_state=0)
        add(f"Own tree (LOPO, depth {a.depth}{', no axes' if a.orientation_free else ''})",
            loso(Xs, y, person, mk),
            note="tree retrained leaving one person out: the honest figure for 'training with my data'")

    # ---- report per model
    P("\n" + "=" * 78 + "\nSUMMARY (criteria: motion detected >= 90 %, still discarded <= 10 %)\n" + "=" * 78)
    P(f"{'model':<44}{'mot.detect.':>12}{'CI95%':>14}{'discard.':>10}{'CI95%':>14}  verdict")
    for r in results:
        m = r["m"]
        ok = m["sens_mov"] >= 0.90 and m["quietas_descartadas"] <= 0.10
        tag = ("*" if r["in_sample"] else " ")
        P(f"{(r['label'] + tag):<44}{m['sens_mov']:>12.3f}"
          f"{'[%.2f,%.2f]' % r['ci_s']:>14}{m['quietas_descartadas']:>10.3f}"
          f"{'[%.2f,%.2f]' % r['ci_d']:>14}  {'PASS' if ok else 'FAIL'}")
    P("  * = trained with this same data: optimistic figure, do not use to decide.")
    P("  CI95 %: bootstrap resampling recordings (more reliable than resampling windows).")

    for r in results:
        m, pred = r["m"], r["pred"]
        P("\n" + "-" * 78 + f"\n{r['label']}" + ("  [IN-SAMPLE, optimistic]" if r["in_sample"] else ""))
        P("  " + r["note"])
        tn, fp, fn, tp = m["cm"].ravel()
        P(f"  matrix  still->valid {tn} | still->not valid {fp} | "
          f"motion->valid {fn} (serious!) | motion->not valid {tp}")
        P(f"  accuracy {m['acc']:.3f} | motion detected {m['sens_mov']:.3f} | "
          f"still discarded {m['quietas_descartadas']:.3f}")
        pp = per_group(y, pred, person)
        P("  per person:")
        for _, row in pp.iterrows():
            P(f"    {row.grupo:<12} motion detected {row.mov_detectado:.3f} | "
              f"still discarded {row.quietas_descartadas:.3f} | error {row.error:.3f}")
        rr = per_group(y, pred, rec).sort_values("error", ascending=False)
        worst = rr[rr.error > 0].head(5)
        if len(worst):
            P("  recordings with the most errors:")
            for _, row in worst.iterrows():
                P(f"    {row.grupo:<40} error {row.error:.2f} ({row.ventanas} windows)")
        else:
            P("  no recording with errors")

    # ---- table by type
    P("\n" + "=" * 78 + "\nERROR BY ACTIVITY TYPE (fraction of misclassified windows)\n" + "=" * 78)
    tab = pd.DataFrame({"n": pd.Series(tipo).value_counts()})
    tab["clase"] = ["motion" if y[tipo == t][0] == 1 else "still" for t in tab.index]
    for i, r in enumerate(results):
        tab[f"M{i + 1}"] = [float((r["pred"][tipo == t] != y[tipo == t]).mean()) for t in tab.index]
    tab = tab.sort_values([c for c in tab.columns if c.startswith("M")][-1], ascending=False)
    for i, r in enumerate(results):
        P(f"  M{i + 1} = {r['label']}{' *' if r['in_sample'] else ''}")
    P(tab.to_string(float_format=lambda v: f"{v:.2f}"))

    # ---- files
    plot_cms(results, os.path.join(a.out, "confusion_matrices.png"))
    df = pd.DataFrame({"grabacion": rec, "persona": person, "tipo": tipo, "real_movimiento": y})
    for i, r in enumerate(results):
        df[f"M{i + 1}"] = r["pred"]
    df.to_csv(os.path.join(a.out, "predicciones_por_ventana.csv"), index=False)
    tab.to_csv(os.path.join(a.out, "error_por_tipo.csv"))
    P(f"\nSaved to {a.out}/: informe.txt, confusion_matrices.png, "
      "predicciones_por_ventana.csv, error_por_tipo.csv")
    log.close()


if __name__ == "__main__":
    main()
